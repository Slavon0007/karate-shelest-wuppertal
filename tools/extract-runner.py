"""Repack an exact run cycle from the supplied GIF; do not redraw its pixels.

The atlas deliberately keeps the original black-on-white frames. The game
applies the yellow theme and white-background transparency in canvas at runtime.
"""
from pathlib import Path
from PIL import Image
import hashlib
import json

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'src/photos/37lJP8S.gif'
OUT = ROOT / 'assets/game'
OUT.mkdir(parents=True, exist_ok=True)

with Image.open(SOURCE) as gif:
    frames = []
    durations = []
    bounds = []
    first = None
    for index in range(gif.n_frames):
        gif.seek(index)
        frame = gif.convert('RGB')
        pixels = frame.tobytes()
        if first is None:
            first = pixels
        elif pixels == first:
            break
        frames.append(frame.copy())
        durations.append(gif.info.get('duration', 60))
        mask = frame.convert('L').point(lambda value: 255 if value < 250 else 0)
        bounds.append(mask.getbbox())

width, height = frames[0].size
atlas = Image.new('RGB', (width * len(frames), height), 'white')
for index, frame in enumerate(frames):
    atlas.paste(frame, (index * width, 0))
source_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
filename = f'runner-run-{source_hash[:10]}.webp'
atlas.save(OUT / filename, 'WEBP', lossless=True, method=6)

# Lossless conversion must retain every original frame pixel.
with Image.open(OUT / filename) as saved:
    for index, original in enumerate(frames):
        restored = saved.crop((index * width, 0, (index + 1) * width, height)).convert('RGB')
        assert restored.tobytes() == original.tobytes()

left = min(box[0] for box in bounds)
top = min(box[1] for box in bounds)
right = max(box[2] for box in bounds)
bottom = max(box[3] for box in bounds)
metadata = {
    'atlas': filename, 'frameWidth': width, 'frameHeight': height,
    'frameCount': len(frames), 'durations': durations, 'cycleMs': sum(durations),
    'crop': {'x': left, 'y': top, 'width': right - left, 'height': bottom - top},
    'anchorX': width / 2, 'sourceSha256': source_hash,
}
(OUT / 'runner-run.js').write_text(
    '// Original GIF frames and timing. Generated by tools/extract-runner.py.\n'
    + 'export const runnerRun = ' + json.dumps(metadata, indent=2) + ';\n', encoding='utf-8')
print(f'Extracted {len(frames)} unchanged frames; cycle {sum(durations)} ms; atlas {(OUT / filename).stat().st_size} bytes.')
print(f'Crop metadata: {metadata["crop"]}; every atlas frame matches its source pixel-for-pixel.')
